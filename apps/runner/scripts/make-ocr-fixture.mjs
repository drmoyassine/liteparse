#!/usr/bin/env node
/**
 * Regenerate test/fixtures/scanned-text.pdf — a single-page PDF whose ONLY
 * content is a JPEG image of rendered text (DCTDecode XObject, no text layer).
 * That is exactly the shape that defeats text-layer extraction and forces the
 * raster+OCR path: a stand-in for a photographed passport page.
 *
 * Rendered with @napi-rs/canvas (run from apps/runner AFTER `npm install`).
 * Output is COMMITTED (~30–80 KB) so the OCR pipeline test needs no canvas at
 * test time. Marker string is asserted by test/ocr-pipeline.test.ts.
 */
import { createCanvas, GlobalFonts } from "@napi-rs/canvas";
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(HERE, "..", "test", "fixtures", "scanned-text.pdf");

export const MARKER = "LITEPARSE RUNNER 7349";

const W = 620;
const H = 240;
const canvas = createCanvas(W, H);
const ctx = canvas.getContext("2d");

// Paper-white with slight off-white noise margin — a scan, not a screen render.
ctx.fillStyle = "#f7f5f0";
ctx.fillRect(0, 0, W, H);

// GlobalFonts.has(f) is the availability probe on @napi-rs/canvas (no .get()).
const family = ["Arial", "DejaVu Sans", "Liberation Sans", "sans-serif"].find((f) =>
  GlobalFonts.has(f),
);

ctx.fillStyle = "#111111";
ctx.font = `600 40px ${family}`;
ctx.fillText(MARKER, 40, 100);
ctx.font = `400 22px ${family}`;
ctx.fillStyle = "#333333";
ctx.fillText("scanned-text fixture — OCR pipeline test", 42, 150);
ctx.fillText("generated by scripts/make-ocr-fixture.mjs", 42, 184);

const jpeg = await canvas.encode("jpeg", 92); // Buffer (DCTDecode stream payload)

// ── hand-assemble a minimal single-page PDF around the JPEG ──────────────────
const objects = [];
objects[1] = "<< /Type /Catalog /Pages 2 0 R >>";
objects[2] = "<< /Type /Pages /Kids [3 0 R] /Count 1 >>";
objects[3] =
  `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${W} ${H}] ` +
  `/Resources << /XObject << /Im0 4 0 R >> >> /Contents 5 0 R >>`;
objects[4] =
  `<< /Type /XObject /Subtype /Image /Width ${W} /Height ${H} ` +
  `/ColorSpace /DeviceRGB /BitsPerComponent 8 /Filter /DCTDecode /Length ${jpeg.length} >>\nstream\n`;
objects[5] = `<< /Length ${`q ${W} 0 0 ${H} 0 0 cm /Im0 Do Q`.length} >>\nstream\n`;

const chunks = [];
let offset = 0;
const push = (buf) => {
  chunks.push(buf);
  offset += buf.length;
};
push(Buffer.from("%PDF-1.7\n", "latin1"));
const offsets = [];
for (let i = 1; i <= 5; i++) {
  offsets[i] = offset;
  if (i === 4) {
    push(Buffer.from(`${i} 0 obj\n${objects[i]}`, "latin1"));
    push(jpeg);
    push(Buffer.from("\nendstream\nendobj\n", "latin1"));
  } else if (i === 5) {
    const content = `q ${W} 0 0 ${H} 0 0 cm /Im0 Do Q`;
    push(Buffer.from(`${i} 0 obj\n${objects[i]}${content}\nendstream\nendobj\n`, "latin1"));
  } else {
    push(Buffer.from(`${i} 0 obj\n${objects[i]}\nendobj\n`, "latin1"));
  }
}
const xrefPos = offset;
let xrefTable = `xref\n0 6\n0000000000 65535 f \n`;
for (let i = 1; i <= 5; i++) xrefTable += `${String(offsets[i]).padStart(10, "0")} 00000 n \n`;
push(Buffer.from(`${xrefTable}trailer\n<< /Size 6 /Root 1 0 R >>\nstartxref\n${xrefPos}\n%%EOF\n`, "latin1"));

writeFileSync(OUT, Buffer.concat(chunks));
console.log(`✓ wrote ${OUT} (${(Buffer.concat(chunks).length / 1024).toFixed(1)} KB, marker "${MARKER}")`);
